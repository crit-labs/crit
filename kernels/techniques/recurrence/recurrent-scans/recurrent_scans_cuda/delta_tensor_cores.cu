constexpr int kTcChunk = 64, kPrepThreads = 256;

struct TcScratch {
    __half* k;    // [k_heads][chunks][64][dk], keys in FP16 (0 past the prompt)
    __half* q;    // [k_heads][chunks][64][dk], queries times the scale
    __half* tb;   // [v_heads][chunks][64][64], T diag(beta)
    __half* p;    // [v_heads][chunks][64][64], the decayed causal q . k
    float* g;     // [v_heads][chunks][64], cumulative log decays
    int* ready;   // [k_heads][chunks]: 1 once pass 1 wrote the chunk (the overlapped launch), then the next item to
                  // take; zeroed before the launch
};

std::size_t tc_part_bytes(const DeltaShape& d, int chunks, int part) {
    const std::size_t c = std::size_t(chunks);
    switch(part) {
    case 0: case 1: return std::size_t(d.k_heads) * c * kTcChunk * d.dk * sizeof(__half);
    case 2: case 3: return std::size_t(d.v_heads) * c * kTcChunk * kTcChunk * sizeof(__half);
    case 4: return std::size_t(d.v_heads) * c * kTcChunk * sizeof(float);
    default: return ((std::size_t(d.k_heads) * c + 1) * sizeof(int) + 15) / 16 * 16;
    }
}

TcScratch tc_split(void* scratch, const DeltaShape& d, int chunks) {
    auto* b = static_cast<unsigned char*>(scratch);
    TcScratch s;
    s.k = reinterpret_cast<__half*>(b); b += tc_part_bytes(d, chunks, 0);
    s.q = reinterpret_cast<__half*>(b); b += tc_part_bytes(d, chunks, 1);
    s.tb = reinterpret_cast<__half*>(b); b += tc_part_bytes(d, chunks, 2);
    s.p = reinterpret_cast<__half*>(b); b += tc_part_bytes(d, chunks, 3);
    s.g = reinterpret_cast<float*>(b); b += tc_part_bytes(d, chunks, 4);
    s.ready = reinterpret_cast<int*>(b);
    return s;
}

