// ---------------------------------------------------------------------------------------------- warp-level pieces
// Four 8 x 8 FP16 matrices from shared memory (crit_kcore/load.cuh's ldmatrix): lanes 8 m .. 8 m + 7 give matrix m's
// rows (16 bytes each).
__device__ __forceinline__ void ldsm4(std::uint32_t (&r)[4], const void* p) { kcore::ldmatrix_x4(r[0], r[1], r[2], r[3], p); }
__device__ __forceinline__ void ldsm4t(std::uint32_t (&r)[4], const void* p) {
    kcore::ldmatrix_x4_trans(r[0], r[1], r[2], r[3], p);
}
// d += a b on FP16 operands with FP32 accumulation (crit_kcore/mma.cuh's m16n8k16, its fragment layouts).
__device__ __forceinline__ void mma16816(float (&d)[4], const std::uint32_t (&a)[4], std::uint32_t b0, std::uint32_t b1) {
    kcore::mma_f16_m16n8k16(d, a[0], a[1], a[2], a[3], b0, b1);
}
using kcore::scan::f16x2;
// Two adjacent 16 x 8 accumulator tiles (columns 0..7 and 8..15) as the A operand over those 16 columns.
__device__ __forceinline__ void as_a(std::uint32_t (&a)[4], const float (&lo)[4], const float (&hi)[4]) {
    kcore::scan::f16_a_of_accumulators(a, lo, hi);
}
using kcore::cp_async16;
using kcore::cp_async_commit;
using kcore::cp_async_wait_all;
// A barrier of the block's first `threads` threads (a multiple of 32), named 1: pass 2's warps inside a larger block.
__device__ __forceinline__ void bar_threads(int threads) { asm volatile("bar.sync 1, %0;\n" :: "r"(threads) : "memory"); }
__device__ __forceinline__ int ld_acquire(const int* p) {
    int v;
    asm volatile("ld.acquire.gpu.global.b32 %0, [%1];\n" : "=r"(v) : "l"(p) : "memory");
    return v;
}

// An FP16 tile of rows of W halfs (64 or 128) in shared memory, its 16-byte chunks XOR-swizzled by the row (the core's
// Swizzle<3, 4, S> on byte offsets: chunk ^ row % 8), so the 8 rows an ldmatrix reads at one chunk fall in 8 different
// bank groups. Offset in halfs of (row, chunk).
template <int W>
__device__ __forceinline__ int swz(int row, int chunk) {
    static_assert(W == 64 || W == 128, "rows of 128 or 256 bytes");
    constexpr int S = W == 128 ? 4 : 3;   // log2(row bytes) - 4
    return static_cast<int>(kcore::swizzle<3, 4, S>(static_cast<std::uint32_t>(row * W * 2 + chunk * 16)) >> 1);
}

// ---------------------------------------------------------------------------------------------- pass 1
// Block per (chunk, key head), 256 threads (8 warps). Shared memory: the FP16 keys and queries (swizzled) for the
// products, then A of two value heads at a time [2][64][kAStride] in the same space.
constexpr int kAStride = 68;
template <int DK>
constexpr std::size_t tc_prep_bytes() {
    const std::size_t kq = std::size_t(2) * kTcChunk * DK * sizeof(__half);
    const std::size_t a = std::size_t(2) * kTcChunk * kAStride * sizeof(float);
    return kq > a ? kq : a;
}

// One (chunk, key head) of pass 1 by the block's 256 threads; with s.ready, its flag is set once every write landed.
template <int DK>
__device__ __forceinline__ void tc_prepare_chunk(const DeltaShape& d, const DeltaInputs& in, int rows, int chunks,
                                                 const TcScratch& s, int c, int kh, unsigned char* smem,
                                                 float (&Gs)[2][kTcChunk], float (&Bs)[2][kTcChunk]) {
    static_assert(DK % 16 == 0 && DK <= 128, "keys in 16-column steps");
    __half* Ks = reinterpret_cast<__half*>(smem);
    __half* Qs = Ks + kTcChunk * DK;
    float* As = reinterpret_cast<float*>(smem);
    const int tid = threadIdx.x, lane = tid & 31, warp = tid >> 5;
    const int t0 = c * kTcChunk, n = min(kTcChunk, rows - t0), ratio = d.v_heads / d.k_heads;
    {   // keys and scaled queries to FP16: the global copies pass 2 reads and the swizzled tiles of the products
        __half* kg = s.k + (std::size_t(kh) * chunks + c) * kTcChunk * DK;
        __half* qg = s.q + (std::size_t(kh) * chunks + c) * kTcChunk * DK;
        for(int e = tid; e < kTcChunk * DK / 4; e += kPrepThreads) {
            const int i = e / (DK / 4), x = (e % (DK / 4)) * 4;
            float kv[4] = {0.f, 0.f, 0.f, 0.f}, qv[4] = {0.f, 0.f, 0.f, 0.f};
            if(i < n) {
                const std::size_t at = std::size_t(t0 + i) * in.qk_stride + std::size_t(kh) * DK + x;
#pragma unroll
                for(int u = 0; u < 4; ++u) { kv[u] = in.k[at + u]; qv[u] = in.q[at + u] * in.scale; }
            }
            const std::uint32_t k01 = f16x2(kv[0], kv[1]), k23 = f16x2(kv[2], kv[3]);
            const std::uint32_t q01 = f16x2(qv[0], qv[1]), q23 = f16x2(qv[2], qv[3]);
            const int at = swz<DK>(i, x >> 3) + (x & 7);
            *reinterpret_cast<uint2*>(Ks + at) = make_uint2(k01, k23);
            *reinterpret_cast<uint2*>(Qs + at) = make_uint2(q01, q23);
            *reinterpret_cast<uint2*>(kg + i * DK + x) = make_uint2(k01, k23);
            *reinterpret_cast<uint2*>(qg + i * DK + x) = make_uint2(q01, q23);
        }
    }
    __syncthreads();
    // K K^T and Q K^T: warp w owns rows 16 (w / 2) .. and columns 32 (w % 2) .. (4 tiles of 8)
    const int mt = warp >> 1, nb = (warp & 1) * 4, g = lane >> 2, tq = lane & 3, lm = lane >> 3, lr = lane & 7;
    float kk[4][4], qk[4][4];
#pragma unroll
    for(int j = 0; j < 4; ++j)
#pragma unroll
        for(int e = 0; e < 4; ++e) kk[j][e] = qk[j][e] = 0.f;
#pragma unroll
    for(int ks = 0; ks < DK / 16; ++ks) {
        std::uint32_t ak[4], aq[4];
        const int arow = 16 * mt + 8 * (lm & 1) + lr, ach = 2 * ks + (lm >> 1);
        ldsm4(ak, Ks + swz<DK>(arow, ach));
        ldsm4(aq, Qs + swz<DK>(arow, ach));
#pragma unroll
        for(int p = 0; p < 2; ++p) {
            std::uint32_t b[4];
            ldsm4(b, Ks + swz<DK>(8 * (nb + 2 * p + (lm >> 1)) + lr, 2 * ks + (lm & 1)));
            mma16816(kk[2 * p], ak, b[0], b[1]);
            mma16816(kk[2 * p + 1], ak, b[2], b[3]);
            mma16816(qk[2 * p], aq, b[0], b[1]);
            mma16816(qk[2 * p + 1], aq, b[2], b[3]);
        }
    }
    __syncthreads();   // the FP16 tiles are dead: their space holds A from here
    for(int h0 = 0; h0 < ratio; h0 += 2) {
        const int heads = min(2, ratio - h0);
        if(tid < 2 * kTcChunk) {
            const int hh = tid / kTcChunk, i = tid % kTcChunk;
            const bool live = hh < heads && i < n;
            const std::size_t at = std::size_t(t0 + i) * in.gate_stride + kh * ratio + h0 + hh;
            Gs[hh][i] = live ? in.log_decay[at] : 0.f;
            Bs[hh][i] = live ? in.beta[at] : 0.f;
        }
        __syncthreads();
        if(tid % kTcChunk == 0 && tid < 2 * kTcChunk)
            for(int i = 1; i < kTcChunk; ++i) Gs[tid / kTcChunk][i] += Gs[tid / kTcChunk][i - 1];
        __syncthreads();
        for(int hh = 0; hh < heads; ++hh) {   // A into shared memory, P and G to global memory
            const int h = kh * ratio + h0 + hh;
            float* A = As + hh * kTcChunk * kAStride;
            __half* P = s.p + (std::size_t(h) * chunks + c) * kTcChunk * kTcChunk;
#pragma unroll
            for(int j = 0; j < 4; ++j)
#pragma unroll
                for(int half = 0; half < 2; ++half) {
                    const int i = 16 * mt + g + 8 * half, jj = 8 * (nb + j) + 2 * tq;
                    float av[2], pv[2];
#pragma unroll
                    for(int u = 0; u < 2; ++u) {
                        const float dec = jj + u <= i ? expf(Gs[hh][i] - Gs[hh][jj + u]) : 0.f;
                        av[u] = jj + u < i ? Bs[hh][i] * dec * kk[j][2 * half + u] : 0.f;
                        pv[u] = jj + u <= i ? dec * qk[j][2 * half + u] : 0.f;
                    }
                    *reinterpret_cast<float2*>(A + i * kAStride + jj) = make_float2(av[0], av[1]);
                    *reinterpret_cast<std::uint32_t*>(P + i * kTcChunk + jj) = f16x2(pv[0], pv[1]);
                }
            if(tid < kTcChunk) s.g[(std::size_t(h) * chunks + c) * kTcChunk + tid] = Gs[hh][tid];
        }
        __syncthreads();
        if(tid < heads * kTcChunk) {   // T = (I + A)^-1 a column a thread by forward substitution, then Tb = T diag(beta)
            const int hh = tid / kTcChunk, j = tid % kTcChunk, h = kh * ratio + h0 + hh;
            const float* A = As + hh * kTcChunk * kAStride;
            float t[kTcChunk];
            kcore::scan::unit_lower_inverse_column<kTcChunk>(A, kAStride, j, t);
            const float bj = Bs[hh][j];
            __half* Tb = s.tb + (std::size_t(h) * chunks + c) * kTcChunk * kTcChunk + j;
#pragma unroll
            for(int i = 0; i < kTcChunk; ++i) Tb[i * kTcChunk] = __float2half_rn(t[i] * bj);
        }
        __syncthreads();
    }
    if(s.ready && tid == 0) {   // the block's writes, ordered by the barrier above, before the flag
        __threadfence();
        atomicExch(s.ready + std::size_t(kh) * chunks + c, 1);
    }
}

template <int DK>
__global__ void __launch_bounds__(kPrepThreads) delta_tc_prepare_kernel(DeltaShape d, DeltaInputs in, int rows, int chunks,
                                                                         TcScratch s) {
    extern __shared__ __align__(16) unsigned char smem[];
    __shared__ float Gs[2][kTcChunk], Bs[2][kTcChunk];
    tc_prepare_chunk<DK>(d, in, rows, chunks, s, blockIdx.x, blockIdx.y, smem, Gs, Bs);
}

// ---------------------------------------------------------------------------------------------- pass 2
template <int DK>
constexpr std::size_t tc_stage_bytes() {
    return (std::size_t(2) * kTcChunk * DK + std::size_t(2) * kTcChunk * kTcChunk) * sizeof(__half) +
           kTcChunk * sizeof(float);
}

// Pass 2 of value head h and value columns 16 WARPS slice .. by the block's first 32 WARPS threads (the others must have
// left). With s.ready, a chunk's tiles are read once pass 1 flagged them.
template <int DK, int WARPS, int STAGES>
__device__ __forceinline__ void tc_scan_slice(const DeltaShape& d, const DeltaInputs& in, int rows, int chunks,
                                              const TcScratch& s, float* state, float* out, std::size_t out_stride, int h,
                                              int slice, unsigned char* smem) {
    static_assert(DK % 16 == 0 && DK <= 128 && (STAGES == 1 || STAGES == 2), "keys in 16-column steps");
    constexpr int KT = DK / 8, THREADS = 32 * WARPS;
    const int kh = h / (d.v_heads / d.k_heads);
    const int warp = threadIdx.x >> 5, lane = threadIdx.x & 31, g = lane >> 2, tq = lane & 3, lm = lane >> 3, lr = lane & 7;
    const int v0 = (slice * WARPS + warp) * 16;
    const bool live = v0 < d.dv;
    auto stage = [&](int st) { return smem + st * tc_stage_bytes<DK>(); };
    auto load = [&](int c, int st) {
        if(s.ready) {   // the overlapped launch: wait for pass 1's flag of this chunk
            if(threadIdx.x == 0)
                while(!ld_acquire(s.ready + std::size_t(kh) * chunks + c)) __nanosleep(200);
            bar_threads(THREADS);
        }
        __half* Ks = reinterpret_cast<__half*>(stage(st));
        __half* Qs = Ks + kTcChunk * DK;
        __half* Ts = Qs + kTcChunk * DK;
        __half* Ps = Ts + kTcChunk * kTcChunk;
        float* Gs = reinterpret_cast<float*>(Ps + kTcChunk * kTcChunk);
        const __half* kg = s.k + (std::size_t(kh) * chunks + c) * kTcChunk * DK;
        const __half* qg = s.q + (std::size_t(kh) * chunks + c) * kTcChunk * DK;
        for(int e = threadIdx.x; e < kTcChunk * DK / 8; e += THREADS) {
            const int row = e / (DK / 8), ch = e % (DK / 8);
            cp_async16(Ks + swz<DK>(row, ch), kg + e * 8);
            cp_async16(Qs + swz<DK>(row, ch), qg + e * 8);
        }
        const std::size_t blk = (std::size_t(h) * chunks + c) * kTcChunk * kTcChunk;
        for(int e = threadIdx.x; e < kTcChunk * kTcChunk / 8; e += THREADS) {
            const int row = e / 8, ch = e % 8;
            cp_async16(Ts + swz<kTcChunk>(row, ch), s.tb + blk + e * 8);
            cp_async16(Ps + swz<kTcChunk>(row, ch), s.p + blk + e * 8);
        }
        if(threadIdx.x < kTcChunk / 4)
            cp_async16(Gs + 4 * threadIdx.x, s.g + (std::size_t(h) * chunks + c) * kTcChunk + 4 * threadIdx.x);
        cp_async_commit();
    };
    // S^T [16 value columns][DK keys] of this warp in MMA accumulators (crit_kcore/scan_chunk.cuh's TransposedState)
    kcore::scan::TransposedState<DK> tile;
    float* sh = state + std::size_t(h) * DK * d.dv;
    tile.load(sh, d.dv, v0, lane, live);
    if(STAGES == 2) load(0, 0);
    for(int c = 0; c < chunks; ++c) {
        const int st = STAGES == 2 ? (c & 1) : 0;
        if(STAGES == 1) load(c, 0);
        cp_async_wait_all();
        bar_threads(THREADS);
        if(STAGES == 2 && c + 1 < chunks) load(c + 1, (c + 1) & 1);
        if(live) {
            const __half* Ks = reinterpret_cast<const __half*>(stage(st));
            const __half* Qs = Ks + kTcChunk * DK;
            const __half* Ts = Qs + kTcChunk * DK;
            const __half* Ps = Ts + kTcChunk * kTcChunk;
            const float* Gs = reinterpret_cast<const float*>(Ps + kTcChunk * kTcChunk);
            const int t0 = c * kTcChunk;
            // V^T of the chunk: (value v0 + g (+ 8), token 8 nt + 2 tq (+ 1)), loads in flight during the products
            float vv[8][4];
            const float* vh = in.v + std::size_t(h) * d.dv + v0 + g;
#pragma unroll
            for(int nt = 0; nt < 8; ++nt)
#pragma unroll
                for(int e = 0; e < 4; ++e) {
                    const int tok = t0 + 8 * nt + 2 * tq + (e & 1);
                    vv[nt][e] = tok < rows ? vh[std::size_t(tok) * in.v_stride + 8 * (e >> 1)] : 0.f;
                }
            // X^T = S^T K^T and S^T Q^T over the chunk's 8 token tiles
            float xa[8][4], oa[8][4];
#pragma unroll
            for(int nt = 0; nt < 8; ++nt)
#pragma unroll
                for(int e = 0; e < 4; ++e) xa[nt][e] = oa[nt][e] = 0.f;
#pragma unroll
            for(int ks = 0; ks < DK / 16; ++ks) {
                std::uint32_t sf[4];
                tile.a_operand(ks, sf);
#pragma unroll
                for(int p = 0; p < 4; ++p) {
                    std::uint32_t bk[4], bq[4];
                    const int row = 8 * (2 * p + (lm >> 1)) + lr, ch = 2 * ks + (lm & 1);
                    ldsm4(bk, Ks + swz<DK>(row, ch));
                    ldsm4(bq, Qs + swz<DK>(row, ch));
                    mma16816(xa[2 * p], sf, bk[0], bk[1]);
                    mma16816(xa[2 * p + 1], sf, bk[2], bk[3]);
                    mma16816(oa[2 * p], sf, bq[0], bq[1]);
                    mma16816(oa[2 * p + 1], sf, bq[2], bq[3]);
                }
            }
            // the decays of the lane's tokens
            const float gl = Gs[kTcChunk - 1], el = expf(gl);
            float eg[8][2], ed[8][2];
#pragma unroll
            for(int nt = 0; nt < 8; ++nt)
#pragma unroll
                for(int u = 0; u < 2; ++u) {
                    const float gt = Gs[8 * nt + 2 * tq + u];
                    eg[nt][u] = expf(gt);
                    ed[nt][u] = expf(gl - gt);
                }
            // Y^T = V^T - X^T diag(e^G) as the A operand over tokens
            std::uint32_t yf[4][4];
#pragma unroll
            for(int nt = 0; nt < 8; ++nt)
#pragma unroll
                for(int e = 0; e < 4; ++e) xa[nt][e] = vv[nt][e] - xa[nt][e] * eg[nt][e & 1];
#pragma unroll
            for(int kt = 0; kt < 4; ++kt) as_a(yf[kt], xa[2 * kt], xa[2 * kt + 1]);
            // delta^T = Y^T Tb^T (Tb lower triangular: token tiles 2p, 2p + 1 need token steps 0 .. p)
            float wa[8][4];
#pragma unroll
            for(int nt = 0; nt < 8; ++nt)
#pragma unroll
                for(int e = 0; e < 4; ++e) wa[nt][e] = 0.f;
#pragma unroll
            for(int p = 0; p < 4; ++p)
#pragma unroll
                for(int kt = 0; kt <= p; ++kt) {
                    std::uint32_t bt[4];
                    ldsm4(bt, Ts + swz<kTcChunk>(8 * (2 * p + (lm >> 1)) + lr, 2 * kt + (lm & 1)));
                    mma16816(wa[2 * p], yf[kt], bt[0], bt[1]);
                    mma16816(wa[2 * p + 1], yf[kt], bt[2], bt[3]);
                }
            // O^T = (S^T Q^T) diag(e^G) + delta^T P^T
            std::uint32_t wf[4][4], wd[4][4];
#pragma unroll
            for(int kt = 0; kt < 4; ++kt) {
                as_a(wf[kt], wa[2 * kt], wa[2 * kt + 1]);
                float lo[4], hi[4];
#pragma unroll
                for(int e = 0; e < 4; ++e) {
                    lo[e] = wa[2 * kt][e] * ed[2 * kt][e & 1];
                    hi[e] = wa[2 * kt + 1][e] * ed[2 * kt + 1][e & 1];
                }
                as_a(wd[kt], lo, hi);
            }
#pragma unroll
            for(int nt = 0; nt < 8; ++nt)
#pragma unroll
                for(int e = 0; e < 4; ++e) oa[nt][e] *= eg[nt][e & 1];
#pragma unroll
            for(int p = 0; p < 4; ++p)
#pragma unroll
                for(int kt = 0; kt <= p; ++kt) {
                    std::uint32_t bp[4];
                    ldsm4(bp, Ps + swz<kTcChunk>(8 * (2 * p + (lm >> 1)) + lr, 2 * kt + (lm & 1)));
                    mma16816(oa[2 * p], wf[kt], bp[0], bp[1]);
                    mma16816(oa[2 * p + 1], wf[kt], bp[2], bp[3]);
                }
            float* oh = out + std::size_t(h) * d.dv + v0 + g;
#pragma unroll
            for(int nt = 0; nt < 8; ++nt)
#pragma unroll
                for(int e = 0; e < 4; ++e) {
                    const int tok = t0 + 8 * nt + 2 * tq + (e & 1);
                    if(tok < rows) oh[std::size_t(tok) * out_stride + 8 * (e >> 1)] = oa[nt][e];
                }
            // S^T = e^{G_last} S^T + (delta^T diag(e^{G_last - G})) K
            tile.scale(el);
#pragma unroll
            for(int kt = 0; kt < 4; ++kt)
#pragma unroll
                for(int q = 0; q < KT / 2; ++q) {
                    std::uint32_t bk[4];
                    ldsm4t(bk, Ks + swz<DK>(16 * kt + 8 * (lm & 1) + lr, 2 * q + (lm >> 1)));
                    mma16816(tile.s[2 * q], wd[kt], bk[0], bk[1]);
                    mma16816(tile.s[2 * q + 1], wd[kt], bk[2], bk[3]);
                }
        }
        if(STAGES == 1) bar_threads(THREADS);
    }
    if(live) tile.store(sh, d.dv, v0, lane);
}

template <int DK, int WARPS, int STAGES>
__global__ void __launch_bounds__(32 * WARPS, 1) delta_tc_scan_kernel(DeltaShape d, DeltaInputs in, int rows, int chunks,
                                                                      TcScratch s, float* state, float* out,
                                                                      std::size_t out_stride) {
    extern __shared__ __align__(16) unsigned char smem[];
    tc_scan_slice<DK, WARPS, STAGES>(d, in, rows, chunks, s, state, out, out_stride, blockIdx.x, blockIdx.y, smem);
}

// Both passes in one launch (the OVERLAP knob): blocks 0 .. scans - 1 run pass 2 (value head, slice), waiting on each
// chunk's flag; the others are pass-1 workers, each taking the next (chunk, key head) item from a counter until none is
// left (items in chunk order, so the chunks pass 2 waits for are written first, and any one worker finishes them all).
// Pass 1, which mostly moves memory, runs on the multiprocessors pass 2's blocks leave free. The host launches it only
// when every block can be resident at once, so a waiting pass-2 block never holds the place the work it waits for
// needs.
template <int DK, int WARPS, int STAGES>
__global__ void __launch_bounds__(kPrepThreads, 1) delta_tc_fused_kernel(DeltaShape d, DeltaInputs in, int rows, int chunks,
                                                                         TcScratch s, float* state, float* out,
                                                                         std::size_t out_stride, int workers, int slices) {
    static_assert(32 * WARPS <= kPrepThreads, "pass 2's warps within the block");
    extern __shared__ __align__(16) unsigned char smem[];
    __shared__ float Gs[2][kTcChunk], Bs[2][kTcChunk];
    __shared__ int next;
    const int b = blockIdx.x, items = chunks * d.k_heads, scans = gridDim.x - workers;
    if(b < scans) {
        if(threadIdx.x >= 32 * WARPS) return;
        const int scan = b;
        tc_scan_slice<DK, WARPS, STAGES>(d, in, rows, chunks, s, state, out, out_stride, scan / slices, scan % slices,
                                         smem);
        return;
    }
    int* counter = s.ready + items;
    for(;;) {   // (each item ends with a barrier, after which every thread has read the item before)
        if(threadIdx.x == 0) next = atomicAdd(counter, 1);
        __syncthreads();
        const int item = next;
        if(item >= items) return;
        tc_prepare_chunk<DK>(d, in, rows, chunks, s, item / d.k_heads, item % d.k_heads, smem, Gs, Bs);
    }
}

template <int DK, int WARPS, int STAGES, int OVERLAP>
cudaError_t delta_tc_launch(const DeltaShape& d, const DeltaInputs& in, int rows, int chunks, TcScratch s,
                            float* state, float* out, std::size_t out_stride, cudaStream_t stream) {
    constexpr std::size_t prep = tc_prep_bytes<DK>(), scan = STAGES * tc_stage_bytes<DK>();
    const int groups = d.dv / 16, slices = (groups + WARPS - 1) / WARPS, scans = d.v_heads * slices;
    if constexpr(OVERLAP != 0) {
        constexpr std::size_t fused = prep > scan ? prep : scan;
        auto kernel = delta_tc_fused_kernel<DK, WARPS, STAGES>;
        cudaError_t e = cudaFuncSetAttribute(kernel, cudaFuncAttributeMaxDynamicSharedMemorySize, static_cast<int>(fused));
        int device = 0, sms = 0, per_sm = 0;
        if(e == cudaSuccess) e = cudaGetDevice(&device);
        if(e == cudaSuccess) e = cudaDeviceGetAttribute(&sms, cudaDevAttrMultiProcessorCount, device);
        if(e == cudaSuccess) e = cudaOccupancyMaxActiveBlocksPerMultiprocessor(&per_sm, kernel, kPrepThreads, fused);
        if(e != cudaSuccess) return e;
        const long long resident = static_cast<long long>(sms) * per_sm, items = static_cast<long long>(chunks) * d.k_heads;
        if(resident > scans && chunks > 1) {   // else the two launches below
            const int workers = static_cast<int>(resident - scans < items ? resident - scans : items);
            e = cudaMemsetAsync(s.ready, 0, (std::size_t(d.k_heads) * chunks + 1) * sizeof(int), stream);
            if(e != cudaSuccess) return e;
            kernel<<<workers + scans, kPrepThreads, fused, stream>>>(d, in, rows, chunks, s, state, out, out_stride,
                                                                     workers, slices);
            return cudaGetLastError();
        }
    }
    s.ready = nullptr;
    cudaError_t e = cudaFuncSetAttribute(delta_tc_prepare_kernel<DK>, cudaFuncAttributeMaxDynamicSharedMemorySize,
                                         static_cast<int>(prep));
    if(e == cudaSuccess)
        e = cudaFuncSetAttribute(delta_tc_scan_kernel<DK, WARPS, STAGES>, cudaFuncAttributeMaxDynamicSharedMemorySize,
                                 static_cast<int>(scan));
    if(e != cudaSuccess) return e;
    delta_tc_prepare_kernel<DK><<<dim3(chunks, d.k_heads), kPrepThreads, prep, stream>>>(d, in, rows, chunks, s);
    delta_tc_scan_kernel<DK, WARPS, STAGES><<<dim3(d.v_heads, slices), 32 * WARPS, scan, stream>>>(
        d, in, rows, chunks, s, state, out, out_stride);
    return cudaGetLastError();
}

template <int DK>
cudaError_t delta_tc(const DeltaShape& d, const DeltaInputs& in, int rows, int chunks, const TcScratch& s, float* state,
                     float* out, std::size_t out_stride, cudaStream_t stream) {
    switch(crit_lookup_delta_prefill_tc(d.k_heads, d.v_heads, d.dk, d.dv, rows)) {
#define CRIT_CASE(index, warps, stages, overlap)                                                                     \
    case index: return delta_tc_launch<DK, warps, stages, overlap>(d, in, rows, chunks, s, state, out, out_stride, stream);
        CRIT_CONFIGS_delta_prefill_tc(CRIT_CASE)
#undef CRIT_CASE
    default: return cudaErrorInvalidConfiguration;
    }
}
#endif  // CRIT_DELTA_TC

