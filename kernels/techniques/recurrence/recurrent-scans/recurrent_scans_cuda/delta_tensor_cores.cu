bool delta_tc_supported(const DeltaShape& d) {
    return d.k_heads > 0 && d.v_heads > 0 && d.v_heads % d.k_heads == 0 && (d.dk == 64 || d.dk == 128) && d.dv > 0 &&
           d.dv % 16 == 0 && d.v_heads <= 65535 && d.k_heads <= 65535;
}

std::size_t delta_tc_scratch_bytes(const DeltaShape& d, int rows) {
    if(!delta_tc_supported(d) || rows < 1) return 0;
    const int chunks = (rows + kTcChunk - 1) / kTcChunk;
    std::size_t total = 0;
    for(int part = 0; part < 6; ++part) total += tc_part_bytes(d, chunks, part);
    return total;
}

cudaError_t enqueue_delta_prefill_tc(const DeltaShape& d, const DeltaInputs& in, int rows, float* state, void* scratch,
                                     float* out, std::size_t out_stride, cudaStream_t stream) {
#if !defined(CRIT_DELTA_TC)
    return cudaErrorNotSupported;
#else
    if(!rows) return cudaSuccess;
    if(!delta_tc_supported(d) || !in.q || !in.k || !in.v || !in.log_decay || !in.beta || !state || !scratch || !out ||
       rows < 0 || out_stride < std::size_t(d.v_heads) * d.dv || (reinterpret_cast<std::uintptr_t>(scratch) & 15u))
        return cudaErrorInvalidValue;
    const int chunks = (rows + kTcChunk - 1) / kTcChunk;
    if(chunks > 2147483647 / kTcChunk) return cudaErrorInvalidValue;
    const TcScratch s = tc_split(scratch, d, chunks);
    return d.dk == 64 ? delta_tc<64>(d, in, rows, chunks, s, state, out, out_stride, stream)
                      : delta_tc<128>(d, in, rows, chunks, s, state, out, out_stride, stream);
#endif
}

