// The gated-delta prefill on tensor cores (structure delta-prefill-tc): the chunked WY / UT-transform algorithm of
// flash-linear-attention's chunk_gated_delta_rule (MIT) and FlashInfer's chunked gated-delta prefill (Apache-2.0),
// written here from the algorithm, FP16 operands with FP32 accumulation and an FP32 state. See recurrent_kernels.h.
//
// Per value head h and 64-token chunk with start state S [dk][dv], cumulative log decays G (G_i = l_0 + .. + l_i), the
// keys K, scaled queries Q and values V of the chunk:
//   A = strictly lower (beta_i e^{G_i - G_j} k_i . k_j),  T = (I + A)^-1,  Tb = T diag(beta)
//   delta = Tb (V - diag(e^G) K S)                       (the chunk's deltas, the recurrence's beta (v - S^T k))
//   O = diag(e^G) Q S + P delta,  P = lower (e^{G_i - G_j} q_i . k_j)
//   S' = e^{G_last} S + (diag(e^{G_last - G}) K)^T delta
// Pass 1 (block per key head and chunk, every chunk at once): K and Q to FP16 (copies pass 2 reads), K K^T and Q K^T
// on tensor cores once for the key head's value heads, then per value head A, T by forward substitution in FP32, Tb, P
// and G. Pass 2 (block per value head and 16 x WARPS value columns, the chunks in order): each warp keeps the transposed
// state slice S^T [16 value columns][dk] in FP32 MMA accumulators, which are also the FP16 A operand of S^T K^T and
// S^T Q^T and, the other way round, take the update; the chunk's K, Q, Tb and P stream through STAGES shared-memory
// stages (cp.async), the values from global memory into registers.
//
// Numerics: products of FP16 operands (keys, queries, the state, Tb, P and the deltas, each rounded once to FP16 per
// chunk) summed in FP32; the inverse and every elementwise step in FP32. Every value must lie in FP16's range
// (|x| < 65504; the state and values in practice): another summation order and rounding than the FP32 passes, within
// 1e-3 + 1e-3|x| of the FP64 recurrence on the bench's prompts. The knobs regroup work only (no value changes).
#include "recurrent_kernels.h"

#include <cuda_fp16.h>

#include <cstdint>

#include "crit_kcore/load.cuh"         // cp.async, ldmatrix, the swizzle
#include "crit_kcore/scan_chunk.cuh"   // the inverse, the accumulators as A operands, the transposed state tile
#include "crit_tuning.h"   // the knobs of the tunable structures (kernel.json), generated by crit's kernel build

