// Integer block expert projections: 4-bit weights (NVFP4's E2M1 codes or INT4, one E4M3 scale per 16) against
// activations quantized per block (E2M1 x 2 for 4-bit activations, INT8 for 8-bit ones), in crit's declared integer
// block order (crit inference/host-expert-arithmetic, host_int.h): each 16-block's dot of the integer values is exact
// (dp4a, int8 tensor cores), block b goes to lane b % 16, lane = fma(float(sum), weight scale * activation scale, lane)
// with the product rounded, blocks in order, the 16 lanes reduced by the halving tree, times the matrix's post.
//
// Two kernels give the same bits for every output: `rows` for decode (a half-warp per output row, every token of a
// job reading the row once) and `gemm` for prompt chunks (int8 m16n8k16 tensor-core tiles, the FP32 step per block in
// registers). crit's CPU rows (host_int.h, AVX-512 VNNI and AVX2) give them too, so an expert's output does not depend
// on the processor or the kernel that computed it: a CPU tier, a device cache and the prompt path agree bit for bit.
// Both are templates whose knobs (threads, rows a half-warp owns, tiles a warp, loads in flight) change only speed;
// crit_tuning.h, generated by crit_kernels.build, picks them per matrix shape and row count.
//
// The quantizers, SiLU and SwiGLU are crit's declared ones (IEEE operations only), so an expert's intermediate is the
// same codes wherever it is computed. CUDA, sm_80 and newer (int8 mma.sync m16n8k16; dp4a).
#pragma once
#include <cstddef>
#include <cstdint>
#include <cuda_runtime.h>

namespace crit::techniques::int_block {

// One matrix as stored, rows layout: codes [rows][cols / 2] (low nibble the even element), E4M3 block scales
// [rows][cols / 16]; a weight is value * scale * post (value E2M1 x 2 or INT4). cols a multiple of 64.
struct Matrix {
    const std::uint8_t* codes = nullptr;
    const std::uint8_t* scales = nullptr;
    int rows = 0, cols = 0;
    float post = 1.0f;
    int int4 = 0;   // 1: INT4 values; 0: E2M1 x 2
};

// Quantized activations: values [row][ld] int8, scales [row][lds] FP32, one per `block` (16 or 32) values.
struct Acts {
    const std::int8_t* values = nullptr;
    const float* scales = nullptr;
    int ld = 0, lds = 0, block = 16;
    int rows = 0;   // activation rows (the tuning table's row count; 0: the job count)
};

// Activations packed as NVFP4 for gemm-native: codes [row][ld] bytes, two E2M1 codes a byte (low nibble the even
// element), and E4M3 scale bytes [row][lds], one per 16 values. Value = 2 x E2M1 (the integer E2M1 x 2 takes) x the
// byte's E4M3 value / global: quantize_nvfp4 writes the E2M1 x 2 quantizer's codes and its scales before the division.
//
// The scale bytes of the activations and of the weights may also be in cuBLASLt's tiled layout (`tiled`; bit 0 the
// activations', bit 1 every matrix's): 128-row x 4-block tiles of 512 bytes, tile (row / 128, block / 4) at byte
// ((row / 128) * (lds / 4) + block / 4) * 512, inside it byte (row % 32) * 16 + (row % 128 / 32) * 4 + block % 4, the
// rows padded to a multiple of 128 (lds the blocks a row, cols / 16, a multiple of 4). Tiled activations need every
// job's first row a multiple of 128.
struct ActsFp4 {
    const std::uint8_t* codes = nullptr;
    const std::uint8_t* scales = nullptr;
    int ld = 0, lds = 0;
    float global = 1.0f;
    int tiled = 0;   // bit 0: the activations' scales tiled; bit 1: every matrix's
    int rows = 0;    // the activation rows codes holds (0: unknown; the native GEMM's tensor maps need it)
};

// A matrix as the host knows it (what the device table's Matrix holds), for gemm-native's tensor maps.
struct HostMatrix {
    const void* codes = nullptr;
    int rows = 0, cols = 0;
};
constexpr int kTiledActs = 1, kTiledWeights = 2;

// gemm-native's output: out [..][ld] in FP32 or BF16 (one rounding, to nearest even, of the FP32 result), each output
// column c times col[c] when col is given (FP32, after the global scale: (sum x post / global) x col[c]).
struct NativeOut {
    void* data = nullptr;
    int ld = 0;
    int bf16 = 0;
    const float* col = nullptr;
    int rows = 0;   // rows the output holds (0: unknown; the TMA-store epilogue needs it)
};

constexpr int kMaxJobTokens = 8;

// Decode: a job is one matrix and up to 8 activation rows; out[out_row[j]][r] for its tokens j and rows r < rows.
struct RowJob {
    int matrix = 0;
    int tokens = 0;
    int act_row[kMaxJobTokens] = {};
    int out_row[kMaxJobTokens] = {};
};

// Prompt: a job is one matrix and `count` consecutive activation rows from `first`; out[first + i][r].
struct GemmJob {
    int matrix = 0;
    int first = 0, count = 0;
};

// matrices: a device array of Matrix; jobs: a device array; out [..][out_ld] FP32.
cudaError_t enqueue_rows(const Matrix* matrices, const RowJob* jobs, int job_count, int max_rows, const Acts& acts,
                         float* out, int out_ld, cudaStream_t stream);
cudaError_t enqueue_gemm(const Matrix* matrices, const GemmJob* jobs, int job_count, int max_rows, int max_count,
                         const Acts& acts, float* out, int out_ld, cudaStream_t stream);
// The same prompt GEMM with shared-memory staging (structure gemm-staged): the same bits as enqueue_gemm. Activation
// rows 16-byte aligned (acts.ld a multiple of 16).
cudaError_t enqueue_gemm_staged(const Matrix* matrices, const GemmJob* jobs, int job_count, int max_rows,
                                int max_count, const Acts& acts, float* out, int out_ld, cudaStream_t stream);

// The prompt GEMM accumulated in the tensor cores (structure gemm-native): NOT the declared order. An output is within
// FP32 accumulation of the exact product, but its bits may depend on the configuration and the job's token count (not
// row invariant); for prompt chunks where speed matters more than matching the decode rows and the CPU rows. int4
// false states that every matrix holds E2M1 weights: an sm_120a device then runs block-scaled FP4 MMAs (an INT4 matrix
// gets NaN outputs); int4 true, and every architecture without block-scaled MMAs, run the s8 MMA a 16-block with the
// scales on the CUDA cores. Activation rows 16-byte aligned (acts.ld a multiple of 16).
// On sm_120a with E2M1 weights the kernel is warp-specialized (a producer warp's TMA copies into a ring of
// mbarrier-guarded stages, the consumer warps' MMAs, persistent CTAs), copying by TMA tensor maps where the host passes
// the table's matrices (host, host_count, at most 4, in table order) and acts.rows, else by cp.async, and may share the
// tiles past its last whole wave out over the CTAs k-iteration by k-iteration (stream-K): it then needs `workspace`
// (gemm_native_workspace's bytes for the same arguments, 16-byte aligned; counters it zeroes on the stream itself). A
// shared tile is summed over its segments in segment order: the same bits on a repeat, and for a fixed max_count and
// max_rows whatever a job's own count.
cudaError_t enqueue_gemm_native(const Matrix* matrices, const GemmJob* jobs, int job_count, int max_rows,
                                int max_count, const ActsFp4& acts, bool int4, const NativeOut& out, void* workspace,
                                std::size_t workspace_bytes, cudaStream_t stream, const HostMatrix* host = nullptr,
                                int host_count = 0);
// The workspace bytes enqueue_gemm_native needs for these arguments on the current device (0: none).
std::size_t gemm_native_workspace(int job_count, int max_rows, int max_count, const ActsFp4& acts, bool int4);

// Declared quantizers of rows x cols FP32 values (x [row][ld_x]) into acts (values [row][acts.ld], scales
// [row][acts.lds]): E2M1 x 2 per 16 with crit's NVFP4 global divisor, or INT8 per acts.block.
cudaError_t enqueue_quantize_e2m1x2(const float* x, int ld_x, int rows, int cols, float global, const Acts& acts,
                                    cudaStream_t stream);
// The E2M1 x 2 quantizer's values packed for gemm-native (ActsFp4): the same codes, the scale bytes undivided.
// x FP32 or (bf16 true) BF16 [rows][ld_x]; acts.tiled bit 0 writes the scales in the tiled layout (rows padded to 128,
// the padding rows' scales left as they are).
cudaError_t enqueue_quantize_nvfp4(const void* x, bool bf16, int ld_x, int rows, int cols, float global,
                                   const ActsFp4& acts, cudaStream_t stream);
cudaError_t enqueue_quantize_int8(const float* x, int ld_x, int rows, int cols, const Acts& acts, cudaStream_t stream);
// out[row][i] = silu(gate_up[row][i]) * gate_up[row][inter + i], declared (crit's swiglu_declared).
cudaError_t enqueue_swiglu(const float* gate_up, int inter, int rows, float* out, cudaStream_t stream);

}  // namespace crit::techniques::int_block
